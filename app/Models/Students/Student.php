<?php

namespace App\Models\Students;

use App\Models\Academic\AcademicSession;
use App\Models\Concerns\Auditable;
use App\Models\Concerns\BelongsToBranch;
use App\Models\User;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Permanent student record. Class/section/roll live on StudentEnrollment (one per session),
 * so history is never overwritten. Students are never hard-deleted: status tracks the lifecycle.
 */
class Student extends Model
{
    use Auditable, BelongsToBranch, HasFactory, SoftDeletes;

    public const STATUSES = ['active', 'transferred', 'withdrawn', 'graduated', 'suspended'];

    public const GENDERS = ['male', 'female', 'other'];

    public const BLOOD_GROUPS = ['A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'];

    protected $fillable = [
        'name', 'name_bn', 'gender', 'date_of_birth', 'birth_registration_no', 'blood_group', 'religion', 'nationality',
        'phone', 'email', 'present_address', 'permanent_address', 'photo_path', 'previous_school', 'admission_date',
        'status', 'status_changed_on', 'medical_notes', 'emergency_contact_name', 'emergency_contact_phone',
    ];

    /** student_code is generated by StudentService and never mass-assigned. */
    protected $guarded = ['student_code', 'user_id'];

    protected $hidden = ['medical_notes'];

    protected array $auditExclude = ['medical_notes'];

    protected function casts(): array
    {
        return [
            'date_of_birth' => 'date',
            'admission_date' => 'date',
            'status_changed_on' => 'date',
            'medical_notes' => 'encrypted',
            'branch_id' => 'integer',
            'institution_id' => 'integer',
            'user_id' => 'integer',
        ];
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function guardians(): BelongsToMany
    {
        return $this->belongsToMany(Guardian::class)
            ->withPivot(['relation', 'is_primary', 'is_emergency_contact'])
            ->withTimestamps();
    }

    public function primaryGuardian(): ?Guardian
    {
        return $this->guardians->firstWhere('pivot.is_primary', true) ?? $this->guardians->first();
    }

    public function enrollments(): HasMany
    {
        return $this->hasMany(StudentEnrollment::class)->latest('enrolled_on');
    }

    /** Enrollment in the branch's current session (if any). */
    public function currentEnrollment(): HasOne
    {
        return $this->hasOne(StudentEnrollment::class)
            ->whereIn('academic_session_id', AcademicSession::query()->current()->select('id'))
            ->latestOfMany('id');
    }

    public function documents(): HasMany
    {
        return $this->hasMany(StudentDocument::class)->latest();
    }

    public function certificates(): HasMany
    {
        return $this->hasMany(Certificate::class);
    }

    public function scopeSearch(Builder $query, ?string $term): Builder
    {
        if (! $term) {
            return $query;
        }

        return $query->where(function (Builder $q) use ($term) {
            $q->where('students.name', 'like', "%{$term}%")
                ->orWhere('students.name_bn', 'like', "%{$term}%")
                ->orWhere('students.student_code', 'like', "%{$term}%")
                ->orWhere('students.birth_registration_no', $term)
                ->orWhere('students.phone', 'like', "%{$term}%");
        });
    }

    public function scopeActive(Builder $query): Builder
    {
        return $query->where('status', 'active');
    }

    public function isActive(): bool
    {
        return $this->status === 'active';
    }

    public function displayName(): string
    {
        return app()->getLocale() === 'bn' && $this->name_bn ? $this->name_bn : $this->name;
    }

    public function ageOn(?\DateTimeInterface $date = null): ?int
    {
        return $this->date_of_birth ? (int) floor($this->date_of_birth->diffInYears($date ?? now())) : null;
    }

    public function initials(): string
    {
        $parts = preg_split('/\s+/', trim($this->name)) ?: [];

        return mb_strtoupper(mb_substr($parts[0] ?? '', 0, 1).mb_substr($parts[1] ?? '', 0, 1));
    }
}
